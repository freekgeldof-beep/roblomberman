Lang.strings = S

-- Roblox locale ids look like "en-us", "pt-br", "zh-cn". Most map on their prefix.
local LOCALE_MAP = {
	["zh-cn"] = "zh_cn", ["zh-hans"] = "zh_cn", ["zh-sg"] = "zh_cn",
	["zh-tw"] = "zh_tw", ["zh-hant"] = "zh_tw", ["zh-hk"] = "zh_tw",
	["tl"] = "fil",
}

function Lang.pick(localeId)
	local id = string.lower(localeId or "en-us"):gsub("_", "-")
	if LOCALE_MAP[id] then
		return LOCALE_MAP[id]
	end
	local prefix = string.match(id, "^(%a+)") or "en"
	if prefix == "zh" then
		return "zh_cn"
	end
	if LOCALE_MAP[prefix] then
		return LOCALE_MAP[prefix]
	end
	return S[prefix] and prefix or "en"
end

-- Translate a message ({k=..., a=...}) or a plain key into the given language
function Lang.t(lang, msg, args)
	if type(msg) == "string" then
		msg = { k = msg, a = args }
	end
	local tbl = S[lang] or S.en
	local text = tbl[msg.k] or S.en[msg.k] or msg.k
	if msg.a then
		text = string.gsub(text, "{(%w+)}", function(name)
			local v = msg.a[name]
			if type(v) == "table" then
				if v.k then
					return Lang.t(lang, v)
				end
				local parts = {}
				for i, item in ipairs(v) do
					parts[i] = Lang.t(lang, item)
				end
				return table.concat(parts, ", ")
			elseif v ~= nil then
				return tostring(v)
			end
			return "{" .. name .. "}"
		end)
	end
	return text
end

return Lang
